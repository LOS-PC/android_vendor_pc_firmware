"""Copies the Intel GPU firmware (i915, xe) from a linux-firmware checkout and generates
Android.bp and intel_gpu.mk.

    git clone --depth 1 https://gitlab.com/kernel-firmware/linux-firmware.git
    ./update.py linux-firmware

Files are the File: entries of the i915 and xe sections of WHENCE. Files that a module of
external/linux-firmware(-mainline) installs are left to that module (see
../wireless/update.py, whose code this reuses), and intel_gpu.mk adds those modules.
WHENCE's Link: entries are older names that kernel 6.12 doesn't request, so they're skipped.
"""

import importlib.util
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

spec = importlib.util.spec_from_file_location(
    "wireless_update", os.path.join(HERE, "..", "wireless", "update.py"))
wireless = importlib.util.module_from_spec(spec)
spec.loader.exec_module(wireless)

# WHENCE driver name: (firmware directory, licence file)
DRIVERS = {"i915": ("i915", "LICENSE.i915"), "xe": ("xe", "LICENSE.xe")}


def parse_whence(path):
    """Returns {driver: (files, section text)} for DRIVERS."""
    sections = {}
    driver = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("Driver:"):
            m = re.match(r"^Driver: *(\S+)", line)
            driver = m.group(1) if m and m.group(1) in DRIVERS else None
            if driver:
                sections.setdefault(driver, ([], []))[1].append(line)
            continue
        if line.startswith("-----"):
            driver = None
        if not driver:
            continue
        files, text = sections[driver]
        text.append(line)
        m = re.match(r"^(?:Raw)?File: *(\S+)", line)
        if m:
            files.append(m.group(1))
    return sections


def bp_items(items):
    return "".join('        "%s",\n' % i for i in items)


def main(tree):
    sections = parse_whence(os.path.join(tree, "WHENCE"))
    installed = wireless.other_installed()

    modules = {}  # driver: files this directory ships
    others = set()
    for driver, (subdir, _) in DRIVERS.items():
        files = sorted(set(sections[driver][0]))
        shutil.rmtree(os.path.join(HERE, subdir), ignore_errors=True)
        modules[driver] = []
        for f in files:
            if f in installed:
                # AOSP's modules come in pairs that install the same paths: <name> to
                # /vendor/firmware and <name>_recovery to recovery's; Android needs <name>
                name = installed[f]
                others.add(name[:-len("_recovery")] if name.endswith("_recovery") else name)
                continue
            os.makedirs(os.path.join(HERE, os.path.dirname(f)), exist_ok=True)
            shutil.copy2(os.path.join(tree, f), os.path.join(HERE, f))
            modules[driver].append(f)

    for _, lic in DRIVERS.values():
        shutil.copy2(os.path.join(tree, "LICENSES", lic), os.path.join(HERE, lic))

    with open(os.path.join(HERE, "WHENCE"), "w", encoding="utf-8") as out:
        out.write("The i915 and xe sections of upstream linux-firmware's WHENCE\n\n")
        for driver in DRIVERS:
            out.write("\n".join(sections[driver][1]).rstrip("\n-") + "\n\n")

    with open(os.path.join(HERE, "Android.bp"), "w", encoding="utf-8") as bp:
        bp.write("""//
// SPDX-FileCopyrightText: The LineageOS Project
// SPDX-License-Identifier: Apache-2.0
//

// Generated by update.py: Intel GPU firmware from upstream linux-firmware, installed to
// /vendor/firmware/i915 and /vendor/firmware/xe, where ueventd serves it to i915 and xe
""")
        for driver, (subdir, lic) in DRIVERS.items():
            bp.write("""
license_kind {
    name: "LicenseRef-%(lic)s",
    conditions: ["by_exception_only"],
    url: "https://gitlab.com/kernel-firmware/linux-firmware/-/blob/main/LICENSES/%(lic)s",
}

license {
    name: "pc_firmware_%(driver)s_license",
    visibility: ["//visibility:private"],
    license_kinds: ["LicenseRef-%(lic)s"],
    license_text: ["%(lic)s"],
}

prebuilt_firmware {
    name: "pc_firmware_%(driver)s",
    licenses: ["pc_firmware_%(driver)s_license"],
    srcs: [
%(srcs)s    ],
    sub_dir: "%(subdir)s",
    vendor: true,
}
""" % {"driver": driver, "lic": lic, "subdir": subdir, "srcs": bp_items(modules[driver])})

    with open(os.path.join(HERE, "intel_gpu.mk"), "w", encoding="utf-8") as mk:
        mk.write("""#
# SPDX-FileCopyrightText: The LineageOS Project
# SPDX-License-Identifier: Apache-2.0
#

# Generated by update.py: the pc_firmware_i915 / xe modules, plus the
# external/linux-firmware(-mainline) modules that install the rest of the files

PRODUCT_PACKAGES += \\
""")
        names = ["pc_firmware_%s" % d for d in DRIVERS] + sorted(others)
        mk.write(" \\\n".join("    " + n for n in names) + "\n")

    for driver, files in modules.items():
        size = sum(os.path.getsize(os.path.join(HERE, f)) for f in files)
        print("%s: %d files (%.1f MB)" % (driver, len(files), size / 1e6))
    print("other modules: " + ", ".join(sorted(others)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
